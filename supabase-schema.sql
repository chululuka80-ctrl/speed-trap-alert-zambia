-- Speed Trap Alert Zambia: Supabase setup
-- Run this in Supabase Dashboard > SQL Editor > New query.
create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('Speed camera','Police checkpoint','Road hazard','Accident')),
  note text not null default '' check (char_length(note) <= 100),
  lat double precision not null check (lat between -90 and 90),
  lon double precision not null check (lon between -180 and 180),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);

alter table public.reports enable row level security;

drop policy if exists "Anyone can read active reports" on public.reports;
create policy "Anyone can read active reports"
on public.reports for select to anon
using (expires_at > now());

drop policy if exists "Anyone can submit a report" on public.reports;
create policy "Anyone can submit a report"
on public.reports for insert to anon
with check (
  expires_at > now()
  and expires_at <= now() + interval '7 hours'
  and char_length(note) <= 100
);
grant select, insert on public.reports to anon;
grant usage, select on sequence public.reports_id_seq to anon;

